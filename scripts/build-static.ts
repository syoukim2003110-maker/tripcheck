/*
 * Builds TripCheck as plain static files for shared hosting (Xserver).
 *
 *   pnpm build:static -- --origin https://your-domain.example
 *
 * Output: dist-static/site/ — upload its contents to the site's public folder.
 *
 * The planner, its feasibility engine and the keyless place lookup all run in
 * the browser, so the only server-side pieces are api/apple.php, a small
 * relay that keeps the Apple Maps key off the page, and api/ai.php, the same
 * for the meal advisor's AI keys. The server routes under app/api/ belong to
 * the Workers deployment and are left out of this build, as is the old
 * planner under app/classic (see scripts/static-build-scope.ts).
 */
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, chmodSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { productionContentSecurityPolicy } from "../lib/security-headers.ts";
import { appleMapsCredentialsFromEnvironment } from "../lib/server/apple-maps.ts";
import { aiConfigPhp, aiKeysFromEnvironment } from "../lib/server/meal-advice-relay.ts";
import { copiedIntoStaticBuild } from "./static-build-scope.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const work = join(root, ".static-build");
const output = join(root, "dist-static", "site");

function argument(name: string) {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const originInput = argument("origin") ?? process.env.SITE_ORIGIN ?? "";
let origin: string;
try {
  const parsed = new URL(originInput);
  if (parsed.protocol !== "https:" && parsed.hostname !== "localhost") throw new Error("https required");
  origin = parsed.origin;
} catch {
  console.error("Usage: pnpm build:static -- --origin https://your-domain.example");
  process.exit(1);
}

/** KEY=value pairs from .env.local, including a quoted multi-line value. */
function localEnvironment() {
  const environment: Record<string, string> = {};
  const path = join(root, ".env.local");
  if (!existsSync(path)) return environment;
  // Names in any case: the owner's file spells one key Claude_API_KEY.
  for (const match of readFileSync(path, "utf8").matchAll(/^([A-Za-z_][A-Za-z0-9_]*)=(?:"([\s\S]*?)"|'([\s\S]*?)'|(.*))$/gm)) {
    environment[match[1]] = (match[2] ?? match[3] ?? match[4] ?? "").trim();
  }
  return environment;
}

const environment = localEnvironment();
// The meal advisor's keys (Claude and/or OpenAI); optional, and server-side
// only. The page shows its AI button only when this build carries a key.
const aiConfig = aiConfigPhp(aiKeysFromEnvironment(environment));

rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
for (const entry of ["app", "lib", "public"]) {
  cpSync(join(root, entry), join(work, entry), {
    recursive: true,
    // Server routes and the old planner stay out of a static site.
    filter: (source) => copiedIntoStaticBuild(root, source),
  });
}
for (const file of ["tsconfig.json", "next-env.d.ts", "package.json"]) cpSync(join(root, file), join(work, file));
writeFileSync(join(work, "next.config.mjs"), `export default ${JSON.stringify({
  output: "export",
  // /ja/index.html rather than /ja.html, so Apache serves /ja with no rewrite.
  trailingSlash: true,
  images: { unoptimized: true },
  typescript: { ignoreBuildErrors: true },
  turbopack: { root },
}, null, 2)};\n`);

const build = spawnSync(process.execPath, [join(root, "node_modules", "next", "dist", "bin", "next"), "build"], {
  cwd: work,
  stdio: "inherit",
  env: {
    // A clean environment: nothing from .env.local (keys, dev relay URL) or
    // from a paid opt-in may leak into files that are published as-is.
    PATH: process.env.PATH ?? "",
    HOME: process.env.HOME ?? "",
    NODE_ENV: "production",
    NEXT_TELEMETRY_DISABLED: "1",
    NEXT_PUBLIC_SITE_ORIGIN: origin,
    NEXT_PUBLIC_APPLE_RELAY_URL: "/api/apple.php",
    NEXT_PUBLIC_TRIPCHECK_STATIC_HOSTING: "1",
    // A flag only, never a key: whether api/ai-config.php is written below.
    ...(aiConfig ? { NEXT_PUBLIC_TRIPCHECK_AI: "1" } : {}),
  },
});
if (build.status !== 0) process.exit(build.status ?? 1);

rmSync(output, { recursive: true, force: true });
mkdirSync(dirname(output), { recursive: true });
cpSync(join(work, "out"), output, { recursive: true });
cpSync(join(root, "deploy", "xserver", "api"), join(output, "api"), { recursive: true });

// 'self' already covers the relay; the header set mirrors the Workers edge.
// Only directives shared hosting reliably allows in .htaccess: the first
// upload used \`Options\` and an \`<If>\` block and the host answered every
// request with 500. Per-directory files replace the conditional block.
writeFileSync(join(output, ".htaccess"), `# TripCheck — generated by scripts/build-static.ts. Do not edit on the server.
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} !on
  RewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
</IfModule>

<IfModule mod_headers.c>
  Header set Content-Security-Policy "${productionContentSecurityPolicy.replace(/"/g, "'")}"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set X-Content-Type-Options "nosniff"
  Header set X-Frame-Options "DENY"
  Header set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=()"
  Header set Cross-Origin-Opener-Policy "same-origin-allow-popups"
  Header set Strict-Transport-Security "max-age=31536000"
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`);
// Build output under /_next/static/ is content-hashed and never changes.
writeFileSync(join(output, "_next", "static", ".htaccess"), `<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`);

const credentials = appleMapsCredentialsFromEnvironment(environment);
// Restaurant photos and budgets (HotPepper Gourmet); optional, and server-side only like the Apple key.
const hotpepperKey = /^[0-9A-Za-z]{8,64}$/.test(environment.HOTPEPPER_API_KEY ?? "") ? environment.HOTPEPPER_API_KEY! : null;
const configPath = join(output, "api", "apple-config.php");
if (credentials) {
  const quote = (value: string) => `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  writeFileSync(configPath, `<?php\n// Generated from .env.local. Keep private; blocked from the web by .htaccess.\nreturn [\n  'team_id' => ${quote(credentials.teamId)},\n  'key_id' => ${quote(credentials.keyId)},\n  'private_key' => ${quote(credentials.privateKey)},\n  'site_origin' => ${quote(origin)},\n${hotpepperKey ? `  'hotpepper_key' => ${quote(hotpepperKey)},\n` : ""}];\n`);
  chmodSync(configPath, 0o600);
}
if (aiConfig) {
  const aiConfigPath = join(output, "api", "ai-config.php");
  writeFileSync(aiConfigPath, aiConfig);
  chmodSync(aiConfigPath, 0o600);
}
// The deploy token lets api/deploy.php unpack an uploaded build. It is made
// once, kept in .env.local, and written next to the script on the server.
let deployToken = environment.TRIPCHECK_DEPLOY_TOKEN ?? "";
if (!/^[0-9a-f]{48}$/.test(deployToken)) {
  deployToken = randomBytes(24).toString("hex");
  appendFileSync(join(root, ".env.local"), `\n# サイト更新用の合言葉(api/deploy.php)。他人に教えないでください。\nTRIPCHECK_DEPLOY_TOKEN=${deployToken}\n`);
}
const deployConfigPath = join(output, "api", "deploy-config.php");
writeFileSync(deployConfigPath, `<?php\n// Generated. Keep private; blocked from the web by .htaccess.\nreturn ['token' => '${deployToken}'];\n`);
chmodSync(deployConfigPath, 0o600);
// A local file the site owner can open; the token is not printed anywhere.
writeFileSync(join(root, "dist-static", "deploy-url.txt"), `${origin}/api/deploy.php?key=${deployToken}\n`);
rmSync(work, { recursive: true, force: true });

// One file to upload. It carries the Apple key, and until it is extracted and
// deleted it sits in a public folder, so its name is not guessable.
for (const stale of readdirSync(join(root, "dist-static"))) {
  if (/^tripcheck-site.*\.zip$/.test(stale)) rmSync(join(root, "dist-static", stale));
}
const zipName = `tripcheck-site-${randomBytes(6).toString("hex")}.zip`;
const zipped = spawnSync("zip", ["-qr", join("..", zipName), "."], { cwd: output, stdio: "inherit" });

console.log(`\nStatic site written to dist-static/site for ${origin}`);
if (zipped.status === 0) {
  console.log(`Upload file: dist-static/${zipName}`);
  console.log("Then run: pnpm deploy:finish   (or open the address in dist-static/deploy-url.txt)");
}
console.log(credentials
  ? "Apple Maps relay: keys included (api/apple-config.php). Do not share this folder."
  : "Apple Maps relay: no keys in .env.local — meals and shop lookup stay off until api/apple-config.php is added.");
console.log(aiConfig
  ? "Meal advisor (AI): keys included (api/ai-config.php). Do not share this folder."
  : "Meal advisor (AI): no ANTHROPIC_API_KEY / OPENAI_API_KEY in .env.local — the AI button is left out of this build.");
